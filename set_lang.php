<?php
// =============================================
// set_lang.php - تبديل اللغة وحفظها في كوكي (موجود في جذر الموقع)
// =============================================

$lang = $_GET['lang'] ?? 'ar';
if (!in_array($lang, ['ar', 'en'], true)) {
    $lang = 'ar';
}

// حفظ الاختيار لمدة سنة، على كل مسارات الموقع
setcookie('site_lang', $lang, time() + 60 * 60 * 24 * 365, '/');

// الرجوع لنفس الصفحة اللي كان فيها المستخدم
$return = $_GET['return'] ?? '/';

// حماية بسيطة: نسمح فقط بمسار داخلي (يبدأ بـ / ومش رابط خارجي)
if (!preg_match('#^/(?!/)#', $return)) {
    $return = '/';
}

header('Location: ' . $return);
exit;
